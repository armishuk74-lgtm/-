export const getUpazilasByDistrict = (districtId: string): Upazila[] => {
  return INITIAL_UPAZILAS.filter((u) => u.districtId === districtId);
};

export const getDistrictById = (districtId: string): District | undefined => {
  return INITIAL_DISTRICTS.find((d) => d.id === districtId);
};

export const getUpazilaById = (upazilaId: string): Upazila | undefined => {
  return INITIAL_UPAZILAS.find((u) => u.id === upazilaId);
};
